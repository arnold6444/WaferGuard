const HANGUL = /[가-힣]/;

export function hasHangul(value) {
  return HANGUL.test(String(value || ""));
}

export function translateLegacyStatic(value) {
  const raw = String(value ?? "");
  const leading = raw.match(/^\s*/)?.[0] || "";
  const trailing = raw.match(/\s*$/)?.[0] || "";
  const core = raw.trim();
  if (!core || !hasHangul(core)) return raw;
  const exact = EXACT.get(core);
  if (exact) return `${leading}${exact}${trailing}`;
  for (const [pattern, render] of RULES) {
    const match = core.match(pattern);
    if (match) return `${leading}${render(...match)}${trailing}`;
  }
  return raw;
}
